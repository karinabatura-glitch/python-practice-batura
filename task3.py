n = float(input("Введіть число"))
m = float(input("Введіть число"))
sum = n + m
minus = n - m
mp = n * m
d = n/m
dd = n // m 
d2 = n % m
step = n ** m
print(f"{n} + {m} = {sum}")
print(f"{n} - {m} = {minus}")
print(f"{n} * {m} = {mp}")
print(f"{n} / {m} = {d}")
print(f"{n} // {m} = {dd}")
print(f"{n} % {m} = {d2}")
print(f"{n} ** {m} = {step}")